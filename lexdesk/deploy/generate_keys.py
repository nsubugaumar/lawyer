"""
Print fresh secret keys for a new LexDesk server, in .env format.

    python3 generate_keys.py >> .env

Run once. Then copy the whole .env somewhere safe and offline (a password
manager, a sealed USB stick in the partners' safe). The vault, field and
search keys cannot be recovered: without them, the encrypted documents and
notes in a backup are unreadable, by design.
"""

import base64
import os
import secrets


def b64(n=32):
    return base64.urlsafe_b64encode(os.urandom(n)).decode()


print("\n# ---- generated by generate_keys.py: back these up offline ----")
print(f"LEXDESK_SECRET_KEY={secrets.token_urlsafe(64)}")
print(f"LEXDESK_JWT_SIGNING_KEY={secrets.token_urlsafe(64)}")
print(f"LEXDESK_VAULT_KEYS=k1:{b64()}")
print(f"LEXDESK_FIELD_KEYS={b64()}")
print(f"LEXDESK_SEARCH_KEY={b64()}")
print(f"POSTGRES_PASSWORD={secrets.token_urlsafe(32)}")
print(f"WHATSAPP_WEBHOOK_VERIFY_TOKEN={secrets.token_urlsafe(24)}")
